def test_review_rejects_empty_body():
    review = SynthesizerAgent().review_entry("X", "", "")
    assert review["verdict"] == "FAIL"
    assert review["quality_score"] == 0
    assert review["provider"] == "heuristic"


def test_review_heuristic_scores_rich_strategy():
    body = """1. Enter LONG when SMA50 > SMA200 and RSI(14) < 30.
2. Entry: market open, 0.01 lots.
3. Stop-loss: below swing low (2*ATR).
4. Take-profit: 2R target at prior resistance.
5. Risk 1% of equity per trade; max 2 concurrent positions."""
    review = SynthesizerAgent().review_entry("SMA Trend", "Momentum", body)
    assert review["provider"] == "heuristic"
    assert review["verdict"] == "PASS"
    assert review["quality_score"] >= 60


